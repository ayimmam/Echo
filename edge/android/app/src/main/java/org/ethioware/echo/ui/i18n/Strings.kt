/** Resolves copy for a locale. Sidaamu Afoo has no wording yet, so it shows English plus a banner. */
class Translator(val locale: AppLocale) {
    /** True when the screen is showing English because the chosen language has no text yet. */
    val showsDraftFallback: Boolean get() = locale == AppLocale.SID

    operator fun invoke(key: S, vararg args: Any): String {
        val template = when (locale) {
            AppLocale.AM -> AmharicStrings[key] ?: EnglishStrings.getValue(key)
            AppLocale.EN, AppLocale.SID -> EnglishStrings.getValue(key)
        }
        return String.format(javaLocale, template, *args)
    }

    val javaLocale: Locale
        get() = when (locale) {
            AppLocale.AM -> Locale.forLanguageTag("am")
            else -> Locale.ENGLISH
        }
}

val LocalT = compositionLocalOf { Translator(AppLocale.EN) }
